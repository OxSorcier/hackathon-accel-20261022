import { createPublicCollector, getWatchCapabilities, KEENABLE_SOURCE_URL } from '../../src/watch/collector.ts';
import { validateCollectionResult } from '../../src/data/validation.ts';

async function main(): Promise<void> {
  const results: object[] = [];
  for (const profile of getWatchCapabilities().profiles ?? []) {
    if (!profile.sourceUrls.includes(KEENABLE_SOURCE_URL)) continue;
    const result = validateCollectionResult(await createPublicCollector({ getApiKey: (): string | undefined => process.env.KEENABLE_API_KEY, limit: 2, maxFetches: 1, timeoutMs: 8000 })(
      { publicTopic: profile.publicTopic, sourceUrls: [KEENABLE_SOURCE_URL] }));
    results.push({ profileId: profile.id, family: profile.family, status: result.status, startedAt: result.startedAt, completedAt: result.completedAt,
      sources: result.sources.map((source) => ({ url: source.url, status: source.status, error: source.error, evidence: source.evidence.map((item) => ({ id: item.id, url: item.url, title: item.title,
        publishedAt: item.publishedAt, contentHash: item.contentHash, provenance: item.provenance, regulation: item.regulation })) })) });
  }
  process.stdout.write(`${JSON.stringify({ observedAt: new Date().toISOString(), environment: 'real Keenable calls, bounded profile probes', results,
    limits: ['A profile is a public search policy, not proof that every relevant event is found', 'Partial and empty results do not establish absence', 'No legal applicability or deadlines activated', 'No connection to real company ERP data', 'No model or proposal generated by this probe'] }, null, 2)}\n`);
}
await main();
